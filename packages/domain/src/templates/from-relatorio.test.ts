const NEW_TEMPLATE = '019966b0-0060-7000-8000-000000000099';

function build(template = standardTemplate({ id: '019966b0-0060-7000-8000-000000000001' }), prefix = '019966b0-0061-7000-8000-') {
  const { relatorioId, drafts } = instantiateTemplate(
    template,
    { id: TEST_PROJECT },
    { service_start: null, service_end: null, existingEquipment: [], responsible_user_id: null },
    { newId: idSequence(prefix), actorId: TEST_USER, companyId: TEST_COMPANY },
  );
  const ops = drafts.map((d) => makeOp({ ...d, device_id: 'tablet-test' }, { newId: idSequence('019966b0-0062-7000-8000-'), now: T0 }));
  const state = replay(ops.map((op, i) => ({ ...op, seq: i + 1 })));
  return { relatorioId, state, snapshot: buildSnapshot(state, relatorioId) };
}

const putOp = (relatorioId: string, path: string, value: unknown, factory = idSequence('019966b0-0063-7000-8000-')) =>
  makeOp(
    { kind: 'put', scope: 'relatorio', company_id: TEST_COMPANY, project_id: null, relatorio_id: relatorioId, path, value: value as JsonValue, prev_op_id: null, batch_id: null, meta: null, actor_id: TEST_USER, device_id: 'tablet-test' },
    { newId: factory, now: T0 },
  );

/** Per location path in skeleton order: the block types and configs in order (what a relatório's structure is). */
function structure(snapshot: Pick<RelatorioSnapshot, 'locations' | 'blocks'>) {
  const live = snapshot.locations.filter((row) => row.removed_at === null);
  const nameOf = (row: LocationRow) => (row.parent_id === null ? row.name : `${live.find((p) => p.id === row.parent_id)!.name} › ${row.name}`);
  return [...live]
    .sort((a, b) => (a.order_key < b.order_key ? -1 : 1))
    .map((row) => ({
      path: nameOf(row),
      agrupar: row.kind === 'cabine' ? row.agrupar_por_tipo : null,
      blocks: locationBlocks(snapshot.blocks, row.id).map((block) => ({ type: block.block_type, config: blockConfigSchema.parse(block.config) })),
    }))
    .sort((a, b) => a.path.localeCompare(b.path));
}

describe('11.3-UNIT templateFromRelatorio over the standard relatório', () => {
  const { snapshot } = build();
  const template = templateFromRelatorio(snapshot, { id: NEW_TEMPLATE, name: 'Porto Seguro' });

  it('parses with templateRowSchema at version 1 on the relatório seed (the current one)', () => {
    expect(templateRowSchema.parse(template)).toBeTruthy();
    expect(snapshot.relatorio.seed_version).toBe(SEED_VERSION);
    expect(template).toMatchObject({ id: NEW_TEMPLATE, name: 'Porto Seguro', version: 1, seed_version: snapshot.relatorio.seed_version, archived_at: null, removed_at: null });
  });

  it('carries the cabines each followed by its colunas, 6 + 17 nodes', () => {
    expect(template.skeleton.filter((node) => node.kind === 'cabine')).toHaveLength(6);
    expect(template.skeleton.filter((node) => node.kind === 'coluna')).toHaveLength(17);
    const firstColuna = template.skeleton.findIndex((node) => node.kind === 'coluna');
    expect(template.skeleton[firstColuna - 1]!.kind).toBe('cabine');
  });

  it('merges runs of equal configs into quantities: 94 sheets in all, sections 7 and 9 never carried', () => {
    const equipment = template.blocks.filter((block) => block.skeleton_location_ref !== null);
    expect(equipment.reduce((sum, block) => sum + block.quantity, 0)).toBe(94);
    expect(equipment.length).toBeLessThan(94);
    const sections = template.blocks.filter((block) => block.skeleton_location_ref === null).map((block) => block.block_type);
    expect(sections).not.toContain('section_7');
    expect(sections).not.toContain('section_9');
    expect(sections).toHaveLength(9);
  });

  it('round-trips through instantiateTemplate: same skeleton, same types and configs per column in order', () => {
    const again = build(template, '019966b0-0064-7000-8000-');
    expect(structure(again.snapshot)).toEqual(structure(snapshot));
    // TAGs are regenerated by suggestTag, never carried.
    expect(again.snapshot.equipment.map((row) => row.tag).sort()).toEqual(snapshot.equipment.map((row) => row.tag).sort());
    expect(again.snapshot.equipment.every((row) => !snapshot.equipment.some((prior) => prior.id === row.id))).toBe(true);
  });
});

describe('11.3-UNIT what is carried and what is not', () => {
  it('skips removed blocks, removed sections and an orphan coluna; keeps agrupar, overrides and section text; no sheet data', () => {
    const { relatorioId, state } = build();
    let s: EntityState = state;
    const snap0 = buildSnapshot(s, relatorioId);
    const subsolo = snap0.locations.find((row) => row.name === '1° Subsolo')!;
    const coluna5 = snap0.locations.find((row) => row.name === 'Coluna 5')!;
    const col5Blocks = locationBlocks(snap0.blocks, coluna5.id);
    const [first, second] = col5Blocks;
    const section3 = snap0.blocks.find((row) => row.block_type === 'section_3')!;
    const section2 = snap0.blocks.find((row) => row.block_type === 'section_2')!;
    const enel = snap0.locations.find((row) => row.kind === 'cabine' && row.id !== subsolo.id)!;
    const factory = idSequence('019966b0-0065-7000-8000-');
    const override = blockConfigSchema.parse(first!.config);
    override.sub_blocks.nameplate = { enabled: false };
    const ops = [
      putOp(relatorioId, `location/${subsolo.id}/agrupar_por_tipo`, true, factory),
      putOp(relatorioId, `block/${first!.id}/config`, { ...override }, factory),
      putOp(relatorioId, `block/${section2.id}/config`, { ...(section2.config as object), section_text: 'Texto próprio {cliente}' }, factory),
      putOp(relatorioId, `block/${second!.id}/not_tested`, { reason: 'solicitacao_cliente', text: null, at: T0.toISOString(), by: TEST_USER }, factory),
      makeOp({ kind: 'remove', scope: 'relatorio', company_id: TEST_COMPANY, project_id: null, relatorio_id: relatorioId, path: `block/${section3.id}/removed_at`, value: null, prev_op_id: null, batch_id: null, meta: null, actor_id: TEST_USER, device_id: 'tablet-test' }, { newId: factory, now: T0 }),
    ];
    for (const op of ops) s = applyOp(s, op);
    const snapshot = buildSnapshot(s, relatorioId);
    // An orphan coluna (its cabine never on this device) and a removed block, fed directly.
    const orphan: LocationRow = { id: '019966b0-0066-7000-8000-000000000001', relatorio_id: relatorioId, parent_id: '019966b0-0066-7000-8000-000000000002', kind: 'coluna', name: 'Solta', order_key: 'a0', removed_at: null };
    const orphanBlock: BlockRow = { ...first!, id: '019966b0-0066-7000-8000-000000000003', location_id: orphan.id };
    const removedBlock: BlockRow = { ...first!, id: '019966b0-0066-7000-8000-000000000004', removed_at: T0.toISOString(), order_key: 'zz' };
    const template = templateFromRelatorio(
      { relatorio: snapshot.relatorio, locations: [...snapshot.locations, orphan], blocks: [...snapshot.blocks, orphanBlock, removedBlock] },
      { id: NEW_TEMPLATE, name: 'T' },
    );
    expect(templateRowSchema.safeParse(template).success).toBe(true);
    expect(template.skeleton.some((node) => node.ref === orphan.id)).toBe(false);
    expect(template.skeleton.find((node) => node.ref === subsolo.id)).toMatchObject({ kind: 'cabine', agrupar_por_tipo: true });
    expect(template.skeleton.find((node) => node.ref === enel.id)).toMatchObject({ agrupar_por_tipo: false });
    const sections = template.blocks.filter((block) => block.skeleton_location_ref === null);
    expect(sections.map((block) => block.block_type)).not.toContain('section_3');
    expect(sections.find((block) => block.block_type === 'section_2')!.section_text).toBe('Texto próprio {cliente}');
    const onCol5 = template.blocks.filter((block) => block.skeleton_location_ref === coluna5.id);
    expect(onCol5[0]!.sub_blocks.nameplate).toEqual({ enabled: false });
    expect(onCol5.reduce((sum, block) => sum + block.quantity, 0)).toBe(col5Blocks.length);
    // No data of the relatório in the row: no ids of equipment, blocks or tags.
    const text = JSON.stringify(template);
    for (const row of snapshot.equipment) {
      expect(text).not.toContain(row.id);
      expect(text).not.toContain(`"${row.tag}"`);
    }
    for (const block of snapshot.blocks) expect(text).not.toContain(block.id);
    expect(text).not.toContain('not_tested');
    expect(text).not.toContain('concluded_by');
    expect(text).not.toContain('solicitacao_cliente');
  });

  it('11.3-AFTER-MOVE: a block moved by a location_id put counts in its new column', () => {
    const { relatorioId, state } = build();
    const snap0 = buildSnapshot(state, relatorioId);
    const coluna5 = snap0.locations.find((row) => row.name === 'Coluna 5')!;
    const coluna9 = snap0.locations.find((row) => row.name === 'Coluna 9')!;
    const moved = locationBlocks(snap0.blocks, coluna5.id)[0]!;
    const count = (t: ReturnType<typeof templateFromRelatorio>, ref: string) => t.blocks.filter((block) => block.skeleton_location_ref === ref).reduce((sum, block) => sum + block.quantity, 0);
    const before = templateFromRelatorio(snap0, { id: NEW_TEMPLATE, name: 'T' });
    const after = buildSnapshot(applyOp(state, putOp(relatorioId, `block/${moved.id}/location_id`, coluna9.id)), relatorioId);
    const template = templateFromRelatorio(after, { id: NEW_TEMPLATE, name: 'T' });
    expect(count(template, coluna5.id)).toBe(count(before, coluna5.id) - 1);
    expect(count(template, coluna9.id)).toBe(count(before, coluna9.id) + 1);
  });

  it('11.4-TEMPLATE-FORMAT: bold, italic and list markup in a relatório section text survive into the template verbatim', () => {
    const { relatorioId, state } = build();
    const section2 = buildSnapshot(state, relatorioId).blocks.find((row) => row.block_type === 'section_2')!;
    const formatted = 'Nota com **negrito** e *itálico* para {cliente}.\n- **Termografia** dos painéis\n1. Limpeza *quando aplicável*';
    const after = buildSnapshot(applyOp(state, putOp(relatorioId, `block/${section2.id}/config`, { ...(section2.config as object), section_text: formatted })), relatorioId);
    const template = templateFromRelatorio(after, { id: NEW_TEMPLATE, name: 'T' });
    expect(templateRowSchema.safeParse(template).success).toBe(true);
    expect(template.blocks.find((block) => block.skeleton_location_ref === null && block.block_type === 'section_2')!.section_text).toBe(formatted);
  });

  it('splits a run longer than MAX_QUANTITY into 99 plus the rest, and still parses', () => {
    const { snapshot } = build();
    const coluna9 = snapshot.locations.find((row) => row.name === 'Coluna 9')!;
    const source = snapshot.blocks.find((row) => row.block_type === 'chave_seccionadora')!;
    const many: BlockRow[] = Array.from({ length: 101 }, (_, i) => ({
      ...source,
      id: `019966b0-0067-7000-8000-${i.toString(16).padStart(12, '0')}`,
      location_id: coluna9.id,
      order_key: `b${i.toString().padStart(3, '0')}`,
    }));
    const template = templateFromRelatorio({ relatorio: snapshot.relatorio, locations: snapshot.locations, blocks: [...snapshot.blocks, ...many] }, { id: NEW_TEMPLATE, name: 'T' });
    expect(template.blocks.filter((block) => block.skeleton_location_ref === coluna9.id).map((block) => block.quantity)).toEqual([MAX_QUANTITY, 2]);
    expect(templateRowSchema.safeParse(template).success).toBe(true);
  });

  it('templateSavedText', () => {
    expect(templateSavedText('Porto Seguro')).toBe('Template Porto Seguro salvo');
  });
});

/*
 * Story 14.2, coordinator review 2026-10-13: the three branches the painel level added to
 * `templateFromRelatorio`, on a hand-built relatório:
 *
 *   Cabine de transformação (local)        two transformers directly on it
 *     Painel de média tensão  (a0)         Coluna 5 (one seccionadora), plus one block on the painel itself
 *     Coluna legado           (a1)         a coluna directly under the local, keyed AFTER the painel; one disjuntor
 *   Cabine removida (local, removed)
 *     Painel órfão                         Coluna 1 (one seccionadora)
 */
describe('14.2-UNIT templateFromRelatorio with painéis', () => {
  const id = (n: number) => `019966b0-0068-7000-8000-${n.toString(16).padStart(12, '0')}`;
  const LOCAL = 1;
  const PAINEL = 2;
  const LEGADO = 3;
  const COLUNA_5 = 4;
  const REMOVIDA = 5;
  const ORFAO = 6;
  const ORFAO_C1 = 7;
  const cabine = (n: number, name: string, order_key: string, removed_at: string | null = null): LocationRow => ({
    id: id(n),
    relatorio_id: TEST_RELATORIO,
    parent_id: null,
    kind: 'cabine',
    name,
    order_key,
    removed_at,
    se: { type: null, primary_kv: null, secondary_kv: null, installed_kva: null },
    env: { altitude_m: null, temperature_c: null, humidity_pct: null },
    agrupar_por_tipo: false,
    funcao: 'transformacao',
  });
  const child = (n: number, kind: 'painel' | 'coluna', name: string, parent: number, order_key: string): LocationRow => ({ id: id(n), relatorio_id: TEST_RELATORIO, parent_id: id(parent), kind, name, order_key, removed_at: null });
  const sheet = (n: number, location: number, type: 'transformador_forca' | 'chave_seccionadora' | 'disjuntor_mt', order_key: string): BlockRow =>
    newEquipmentBlock({ blockId: id(1000 + n), equipmentId: id(2000 + n), relatorioId: TEST_RELATORIO, projectId: TEST_PROJECT, locationId: id(location), type, tag: `T-${n}`, seedVersion: 'v1', orderKey: order_key }).block;

  const locations: LocationRow[] = [
    cabine(LOCAL, 'Cabine de transformação', 'a0'),
    child(PAINEL, 'painel', 'Painel de média tensão', LOCAL, 'a0'),
    child(LEGADO, 'coluna', 'Coluna legado', LOCAL, 'a1'),
    child(COLUNA_5, 'coluna', 'Coluna 5', PAINEL, 'a0'),
    cabine(REMOVIDA, 'Cabine removida', 'a1', T0.toISOString()),
    child(ORFAO, 'painel', 'Painel órfão', REMOVIDA, 'a0'),
    child(ORFAO_C1, 'coluna', 'Coluna 1', ORFAO, 'a0'),
  ];
  const blocks: BlockRow[] = [
    sheet(1, LOCAL, 'transformador_forca', 'a0'),
    sheet(2, LOCAL, 'transformador_forca', 'a1'),
    sheet(3, LEGADO, 'disjuntor_mt', 'a0'),
    sheet(4, COLUNA_5, 'chave_seccionadora', 'a0'),
    // A block the fold let through on the painel itself (its location was not in state when the op was applied).
    sheet(5, PAINEL, 'chave_seccionadora', 'a0'),
    sheet(6, ORFAO_C1, 'chave_seccionadora', 'a0'),
  ];
  const template = templateFromRelatorio({ relatorio: { seed_version: 'v1' }, locations, blocks }, { id: NEW_TEMPLATE, name: 'Com painéis' });
  const placedOn = (ref: number) => template.blocks.filter((block) => block.skeleton_location_ref === id(ref)).map((block) => [block.block_type, block.quantity]);

  it('parses, and carries the Função of the local', () => {
    expect(templateRowSchema.safeParse(template).success).toBe(true);
    expect(template.skeleton[0]).toMatchObject({ kind: 'cabine', name: 'Cabine de transformação', funcao: 'transformacao' });
  });

  it('a coluna directly under the local keyed after a painel still comes before the painel: local, its colunas, then each painel with its colunas', () => {
    expect(template.skeleton.map((node) => [node.kind, node.name, node.parent_ref])).toEqual([
      ['cabine', 'Cabine de transformação', null],
      ['coluna', 'Coluna legado', id(LOCAL)],
      ['painel', 'Painel de média tensão', id(LOCAL)],
      ['coluna', 'Coluna 5', id(PAINEL)],
    ]);
    expect(placedOn(LOCAL)).toEqual([['transformador_forca', 2]]);
    expect(placedOn(LEGADO)).toEqual([['disjuntor_mt', 1]]);
    expect(placedOn(COLUNA_5)).toEqual([['chave_seccionadora', 1]]);
  });

  it('a painel whose cabine is removed is skipped with its colunas and their blocks', () => {
    const refs = template.skeleton.map((node) => node.ref);
    for (const gone of [REMOVIDA, ORFAO, ORFAO_C1]) expect(refs).not.toContain(id(gone));
    expect(placedOn(ORFAO_C1)).toEqual([]);
    expect(placedOn(ORFAO)).toEqual([]);
  });

  it('a block sitting on a painel is dropped: a painel node never takes one', () => {
    expect(placedOn(PAINEL)).toEqual([]);
    // Every placed block names the local or a coluna, and the five live sheets off the painel are all there.
    const kinds = new Map(template.skeleton.map((node) => [node.ref, node.kind]));
    const placed = template.blocks.filter((block) => block.skeleton_location_ref !== null);
    expect(placed.every((block) => kinds.get(block.skeleton_location_ref!) !== 'painel')).toBe(true);
    expect(placed.reduce((sum, block) => sum + block.quantity, 0)).toBe(4);
  });
});

describe('14.3-UNIT how templates reach the current seed version', () => {
  const EARLIER = Object.keys(SEED_VERSIONS).filter((version) => version !== SEED_VERSION);
  const TEMPLATE = '019966b0-0069-7000-8000-000000000001';

  it('the bundle ships v1 to v5 before the current v6', () => {
    expect(SEED_VERSION).toBe('v6');
    expect(EARLIER).toEqual(['v1', 'v2', 'v3', 'v4', 'v5']);
  });

  it.each(['v1', 'v2', 'v3', 'v4', 'v5'])('templateSeedUpgrade: the standard template of %s validates on the current version and moves to it', (version) => {
    const row = standardTemplate({ id: TEMPLATE, seedVersion: version });
    expect(row.seed_version).toBe(version);
    expect(templateSeedUpgrade(row)).toBe(SEED_VERSION);
    // What the server step writes: the same row with only `seed_version` moved.
    const moved = { ...row, seed_version: SEED_VERSION };
    expect(templateRowSchema.safeParse(moved).success).toBe(true);
    expect(templateRowSchema.parse(moved)).toEqual({ ...row, seed_version: SEED_VERSION });
    expect(templateSeedUpgrade(moved)).toBeNull();
  });

  it.each(['v1', 'v2', 'v3', 'v4'])('templateSeedUpgrade: every default config of %s, with each subtype and role, validates on the current version', (version) => {
    const blocks: TemplateBlock[] = SECTION_BLOCK_TYPES.map((type) => ({ ...defaultBlockConfig(version, type), quantity: 1, skeleton_location_ref: null, section_text: null }));
    // Every type the version ships: the eight on v1 to v4 (Story 14.5: v5 is their superset).
    expect(equipmentTypesOf(version)).toHaveLength(8);
    for (const type of equipmentTypesOf(version)) {
      const variants = [{}, ...getDefinition(version, 'cabine_primaria', type).subtypes.map((subtype) => ({ subtype: subtype.key })), { role: 'entrada' as const }, { role: 'saida' as const }, { role: 'alimentacao' as const }];
      for (const options of variants) blocks.push({ ...defaultBlockConfig(version, type, options), quantity: 1, skeleton_location_ref: 'local', section_text: null });
    }
    const row = { ...emptyTemplate(TEMPLATE, version), blocks, skeleton: [{ ref: 'local', kind: 'cabine' as const, parent_ref: null, name: 'Local', agrupar_por_tipo: false }] };
    expect(templateRowSchema.safeParse(row).success).toBe(true);
    expect(blocks.length).toBeGreaterThan(SECTION_BLOCK_TYPES.length + equipmentTypesOf(version).length * 4);
    expect(templateSeedUpgrade(row)).toBe(SEED_VERSION);
  });

  it('templateSeedUpgrade: null when already current, on a version this bundle does not ship, and when the row would not validate there', () => {
    const current = standardTemplate({ id: TEMPLATE });
    expect(templateSeedUpgrade(current)).toBeNull();
    expect(templateSeedUpgrade({ ...current, seed_version: 'v99' })).toBeNull();
    expect(templateSeedUpgrade({ ...current, seed_version: '' })).toBeNull();
    expect(templateSeedUpgrade({ ...current, seed_version: 'toString' })).toBeNull();
    // A row that fails the current version's row check stays where it is (the server step skips and logs it).
    const v3 = standardTemplate({ id: TEMPLATE, seedVersion: 'v3' });
    const broken = { ...v3, blocks: v3.blocks.map((block, i) => (i === v3.blocks.length - 1 ? { ...block, section_text: 'x' } : block)) };
    expect(templateSeedUpgrade(broken)).toBeNull();
    const orphanParent = { ...v3, skeleton: [...v3.skeleton, { ref: 'solta', kind: 'coluna' as const, parent_ref: 'ausente', name: 'Coluna solta' }] };
    expect(templateSeedUpgrade(orphanParent)).toBeNull();
    // An empty template and one with only a skeleton move too.
    expect(templateSeedUpgrade(emptyTemplate(TEMPLATE, 'v1'))).toBe(SEED_VERSION);
    expect(templateSeedUpgrade({ seed_version: 'v2', blocks: [], skeleton: v3.skeleton })).toBe(SEED_VERSION);
  });

  it.each(['v1', 'v2', 'v3'])('a template saved from a relatório on %s is born on the current version, with the same structure', (version) => {
    const { snapshot } = build(standardTemplate({ id: '019966b0-0060-7000-8000-000000000001', seedVersion: version }), '019966b0-006a-7000-8000-');
    expect(snapshot.relatorio.seed_version).toBe(version);
    const saved = templateFromRelatorio(snapshot, { id: NEW_TEMPLATE, name: 'De um relatório antigo' });
    expect(saved.seed_version).toBe(SEED_VERSION);
    expect(templateRowSchema.safeParse(saved).success).toBe(true);
    expect(saved.blocks.filter((block) => block.skeleton_location_ref !== null).reduce((sum, block) => sum + block.quantity, 0)).toBe(94);
    // The relatório itself is not touched: its row and its blocks stay on the version they were made with.
    expect(snapshot.relatorio.seed_version).toBe(version);
    expect(new Set(snapshot.blocks.map((block) => block.seed_version))).toEqual(new Set([version]));
    // A relatório made from the saved template is born on the current version.
    const again = build(saved, '019966b0-006b-7000-8000-');
    expect(again.snapshot.relatorio.seed_version).toBe(SEED_VERSION);
    expect(structure(again.snapshot)).toEqual(structure(snapshot));
  });

  it('a relatório on a version this bundle does not ship keeps its own version on the saved template', () => {
    const { snapshot } = build();
    const saved = templateFromRelatorio({ ...snapshot, relatorio: { seed_version: 'v99' }, blocks: [] }, { id: NEW_TEMPLATE, name: 'Futuro' });
    expect(saved.seed_version).toBe('v99');
  });
});
